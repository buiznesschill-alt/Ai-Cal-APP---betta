const I18nContext = createContext<{ locale: Locale; t: (k: string) => string; setLocale: (l: Locale) => void }>({
  locale: "sk",
  t: (k) => k,
  setLocale: () => {},
});

export function I18nProvider({ children, initialLocale }: { children: React.ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale || "sk");
  useEffect(() => {
    const saved = localStorage.getItem("fitcal_locale") as Locale | null;
    if (saved && (saved === "sk" || saved === "en")) setLocaleState(saved);
  }, []);
  const setLocale = (l: Locale) => {
    setLocaleState(l);
    localStorage.setItem("fitcal_locale", l);
    document.cookie = `fitcal_locale=${l}; Path=/; Max-Age=${60 * 60 * 24 * 365}; SameSite=Lax`;
    fetch("/api/settings", { method: "PATCH", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ locale: l }) }).catch(() => {});
  };
  const t = (key: string) => dictionaries[locale][key] || dictionaries["en"][key] || key;
  return <I18nContext.Provider value={{ locale, t, setLocale }}>{children}</I18nContext.Provider>;
}
export function useI18n() {
  return useContext(I18nContext);
}
